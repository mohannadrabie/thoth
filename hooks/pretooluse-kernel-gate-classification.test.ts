// The marker verbs and identity-target grammar are the plan's own encoding (section 4).
const MARKER_READ_ONLY = "tool-class:read-only";
const MARKER_REMOTE_MUTATING = "tool-class:remote-mutating";
const BASH_GET = "kubectl get pod/x --context=c";
const BASH_DELETE = "kubectl delete pods/x --context=c";

type Effect = "allow" | "deny";
interface TestRule {
  id: string;
  effect: Effect;
  verbs?: string[];
  targets?: string[];
  rationale?: string;
}
function policyOf(opts: { defaultOutcome?: Effect; rules?: TestRule[] }): Record<string, unknown> {
  return {
    version: "0.0.0-s7-h-test",
    ...(opts.defaultOutcome === undefined ? {} : { defaultOutcome: opts.defaultOutcome }),
    rules: opts.rules ?? [],
  };
}

function assertSilentAllow(run: GateRun, what: string): void {
  assert.ok(isSilentAllow(run), `${what}: expected an ALLOW that emits nothing (exit 0, empty stdout, empty stderr); got ${describeRun(run)}`);
}
function assertPolicyDenied(run: GateRun, what: string): void {
  assert.ok(wasPolicyDenied(run), `${what}: expected a strict policy DENY (exit 0 plus an explicit deny JSON with a reason; exit 2 or a crash does not count); got ${describeRun(run)}`);
}
/** A deny that the KERNEL produced for an unclassified/unresolved MCP call (POL-05), as opposed to
 * the pre-kernel refusal for an unroutable tool_name. */
function assertKernelUnresolvedDeny(run: GateRun, what: string): void {
  assertPolicyDenied(run, what);
  assert.match(denyReason(run), /POL-05/, `${what}: expected the deny to come from the kernel's POL-05 rule (an unclassified or unresolved MCP call is denied fail-closed), not a generic refusal; got reason=${JSON.stringify(denyReason(run))}`);
}

