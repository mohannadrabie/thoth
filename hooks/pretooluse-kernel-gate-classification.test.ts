test("AC-H8: fixture entries naming Write, Edit, Task, Bash as read-only have no effect (gate scope is Bash plus mcp__ only): Write, Edit, Task stay denied; Bash delete is treated exactly as with no such entries", () => {
  const planted = createGateSandbox();
  const plainBaseline = createGateSandbox();
  planted.editFixture((fixture) => {
    for (const name of ["Write", "Edit", "Task", "Bash"]) fixture.centralLayer.tools.push({ name, class: "read-only" });
  });
  for (const toolName of ["Write", "Edit", "Task"]) {
    assertPolicyDenied(planted.call(toolName, {}), `tool_name ${toolName} with a read-only fixture entry of the same name`);
  }
  const withEntries = planted.bash(BASH_DELETE);
  const withoutEntries = plainBaseline.bash(BASH_DELETE);
  assertSilentAllow(withoutEntries, `Bash "${BASH_DELETE}" with no such entries (posture allow, resolved delete, no rule)`);
  assertSilentAllow(withEntries, `Bash "${BASH_DELETE}" with entries naming Bash and built-ins`);
  assert.deepEqual(classify(withEntries), classify(withoutEntries), "the planted built-in entries must not change the verdict of any call");
});

