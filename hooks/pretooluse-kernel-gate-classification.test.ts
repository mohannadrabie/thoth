test("AC-H7: class is rule data, both directions: a project deny rule on the remote-mutating marker plus the first fixture entry's server denies that server's MCP call; flipping the entry to read-only stops the deny", () => {
  const sb = createGateSandbox();
  const name = firstCommittedEntryName();
  const rationale = "H7-CLASS-RULE-DENY-MARKER";
  sb.writeProjectPolicy(
    policyOf({ rules: [{ id: "h7-deny-remote-mutating-server", effect: "deny", verbs: [MARKER_REMOTE_MUTATING], targets: [`mcp/${name}/`], rationale }] }),
  );
  // direction 1: the committed fixture, UNMODIFIED. If the committed entry were reclassified this
  // answer key is what surfaces it (mutant M2: the first committed entry flipped to read-only).
  const denied = sb.mcp(name, "x");
  assertPolicyDenied(denied, `mcp__${name}__x with the fixture as committed`);
  assert.equal(denyReason(denied), rationale, "the deny must come from the project rule keyed on the marker verb (the rule's own rationale is the reason), not from a generic refusal");
  // direction 2: the sandbox fixture flips this entry to read-only; the same rule no longer matches
  sb.editFixture((fixture) => {
    const entry = fixture.centralLayer.tools.find((t) => t.name === name);
    assert.ok(entry !== undefined, "the sandbox fixture must still list the first committed entry");
    entry.class = "read-only";
  });
  assertSilentAllow(sb.mcp(name, "x"), `mcp__${name}__x after the sandbox fixture flips the entry to read-only`);
});

