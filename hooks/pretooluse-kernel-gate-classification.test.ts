// Black-box acceptance tests for the S7 kernel-gate classification story (Issue #93, #288
// preconditions, #107), hook layer: `hooks/pretooluse-kernel-gate.mjs` after it consumes the
// loader's resolved rules and posture and classifies `mcp__` tool calls. Written FIRST by
// test-writer, before any production code exists (docs/plans/s7-kernel-gate-classification-
// phase1-2026-09-26.md revision 3, section 7 "H: hook black-box (TW)", section 11).
//
// Every check runs in a registry-pinned copy-tree sandbox (hooks/test-support/gate-sandbox.ts) and
// spawns the copied hook exactly as Claude Code does (node script, JSON on stdin, decision read
// from stdout and the exit code). Read that helper's header for the strict outcome rules:
//   - a DENY is exit 0 plus an explicit deny JSON (a crash or exit 2 is NOT a deny);
//   - an ALLOW is exit 0 with EMPTY stdout and EMPTY stderr (Q-B: the gate emits nothing on allow).
//
// TRACEABILITY. Each test title starts with `AC-H<n>`, the plan's own check id (H1..H13 plus
// H11b, 14 checks). The receipt's "mapped n/n" count is generated by grepping these tags.
//
// NAMES. No committed fixture entry name is typed anywhere in this file (PC-11, G19,
// THOTH-ADR-0001 rule 1): committed entries are read from the fixture at run time; every other
// server name below is a stand-in that is not a committed entry ("docs", "my server", ...).
//
// KNOWN LIMITS, disclosed. (1) The plan's H3/H4 say the deny reason "names the unresolved cause".
// The kernel's POL-05 rule reports an opaque record with the fixed reason "POL-05: mutating
// action's source is opaque" (kernel.ts pol05Rule checks `source` before it reads `unresolved`),
// so the cause text is NOT in the reason as the plan's record shape stands. These tests therefore
// assert the deny came from POL-05 (not from the pre-kernel refusal for an unroutable name) and do
// not assert cause wording; see the report for the plan defect. (2) H13 needs the gate module's
// export name and result shape, which the plan does not define; it derives the export name from
// the hook's own import at run time and mutates the REAL gate result shape-agnostically.
