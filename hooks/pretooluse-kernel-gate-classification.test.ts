test("AC-H6: a corrupt project policy denies Bash and MCP calls (strict); the reason names layer project and kind json-parse-error and never carries the file bytes", () => {
  const sb = createGateSandbox();
  // A bare token where a rule object belongs: V8's JSON.parse message echoes a window of the source
  // around the error, so an implementation that forwards the raw loader message would carry this
  // canary (and the file path the loader prefixes to its message) into the deny reason.
  const canary = "CANARY-ZQX-7431-DO-NOT-ECHO";
  sb.writeProjectPolicy(`{ "version": "v", "rules": [ ${canary} ] }`);
  const calls: [string, GateRun][] = [
    ["Bash", sb.bash(BASH_GET)],
    ["MCP call", sb.mcp(firstCommittedEntryName(), "x")],
  ];
  for (const [label, run] of calls) {
    assertPolicyDenied(run, `${label} with a corrupt project policy`);
    const reason = denyReason(run);
    assert.match(reason, /project/, `${label}: the reason must name the failing layer (project); got ${JSON.stringify(reason)}`);
    assert.match(reason, /json-parse-error/, `${label}: the reason must name the failure kind (json-parse-error); got ${JSON.stringify(reason)}`);
    assert.ok(!reason.includes(canary), `${label}: the reason must NOT contain the policy file's bytes (layer and kind only); got ${JSON.stringify(reason)}`);
    assert.ok(!reason.includes(sb.root), `${label}: the reason must NOT carry the loader's raw message (it prefixes the policy file's path); got ${JSON.stringify(reason)}`);
    assert.ok(!run.stdout.includes(canary), `${label}: stdout must NOT contain the policy file's bytes`);
  }
});

