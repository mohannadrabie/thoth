interface NameCase {
  label: string;
  entries: { name: string; class: string }[];
  server: string;
  tool: string;
  expect: "allow" | "deny";
}

test("AC-H4: server-name mapping is injective-or-unresolved: stand-in entries admitted only when solely [A-Za-z0-9-], exact lookup, ambiguous names denied by POL-05", () => {
  const sb = createGateSandbox();
  const committed = firstCommittedEntryName();
  const ro = "read-only";
  const cases: NameCase[] = [
    // the control: an admitted stand-in resolves
    { label: "stand-in docs is admitted (control)", entries: [{ name: "docs", class: ro }], server: "docs", tool: "x", expect: "allow" },
    // R-D: a tool segment with a triple underscore, or a second double underscore, is ambiguous
    { label: "mcp__docs___x (triple underscore) is unresolved", entries: [{ name: "docs", class: ro }], server: "docs", tool: "_x", expect: "deny" },
    { label: "mcp__docs__evil__x (second double underscore) is unresolved", entries: [{ name: "docs", class: ro }], server: "docs", tool: "evil__x", expect: "deny" },
    // exact lookup only: no prefix and no longest match (kills the prefix-lookup mutant at hook level too)
    { label: "mcp__docs-evil__x is not classified by entry docs", entries: [{ name: "docs", class: ro }], server: "docs-evil", tool: "x", expect: "deny" },
    { label: "mcp__docsevil__x is not classified by entry docs", entries: [{ name: "docs", class: ro }], server: "docsevil", tool: "x", expect: "deny" },
    { label: "mcp__docs2__x is not classified by entry docs", entries: [{ name: "docs", class: ro }], server: "docs2", tool: "x", expect: "deny" },
    { label: "mcp__doc__x (a proper prefix of docs) is not classified", entries: [{ name: "docs", class: ro }], server: "doc", tool: "x", expect: "deny" },
    // the charset admission rule: a rejected entry classifies nothing
    { label: 'stand-in entry "my server" is rejected: mcp__my_server__x denied', entries: [{ name: "my server", class: ro }], server: "my_server", tool: "x", expect: "deny" },
    { label: 'entries "my server" plus my_server: mcp__my_server__x denied', entries: [{ name: "my server", class: ro }, { name: "my_server", class: ro }], server: "my_server", tool: "x", expect: "deny" },
    { label: "stand-in entry my_server alone: mcp__my_server__x denied (underscore names are not admitted)", entries: [{ name: "my_server", class: ro }], server: "my_server", tool: "x", expect: "deny" },
    // the first committed entry: the same name resolves with a plain tool segment (control) and is
    // denied when the tool segment holds a triple underscore
    { label: "the first committed entry with a plain tool segment resolves (control)", entries: [], server: committed, tool: "x", expect: "allow" },
    { label: "the first committed entry with a triple-underscore tool segment is denied", entries: [], server: committed, tool: "a___b", expect: "deny" },
  ];
  for (const c of cases) {
    // an empty `entries` list means: the committed fixture entries, read from the committed file
    sb.setEntries(c.entries.length > 0 ? c.entries : readCommittedFixture().centralLayer.tools);
    const run = sb.mcp(c.server, c.tool);
    const what = `${c.label} (mcp__${c.server}__${c.tool})`;
    if (c.expect === "allow") assertSilentAllow(run, what);
    else assertKernelUnresolvedDeny(run, what);
  }
});

