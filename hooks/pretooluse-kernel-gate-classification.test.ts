/** Names the hook imports from the gate module (export names are not defined by the plan; derived
 * from the hook's own import statement at run time). */
function gateImportNames(hookSource: string): string[] | undefined {
  const match = /import\s*\{([^}]*)\}\s*from\s*["']\.\.\/src\/policy\/gate\/decide-tool-call\.ts["']/.exec(hookSource);
  if (match === null) return undefined;
  const names = (match[1] ?? "")
    .split(",")
    .map((part) => (part.trim().split(/\s+as\s+/)[0] ?? "").trim())
    .filter((n) => n.length > 0);
  return names.length > 0 ? names : undefined;
}

/** A pass-through wrapper around the REAL gate module (renamed to *.real.ts) that, per H13_MODE,
 * replaces the real result with an odd shape. Shape-agnostic: it mutates whatever the real gate
 * returned. It records what it did in H13_MARK so the test can prove the mutation was applied. */
function wrapperSource(names: string[]): string {
  const exportsBlock = names
    .map((n) => `export const ${n} = typeof real.${n} === "function" ? wrap(real.${n}) : real.${n};`)
    .join("\n");
  return `import * as real from "./decide-tool-call.real.ts";
import fs from "node:fs";
const MODE = process.env.H13_MODE ?? "control";
const MARK = process.env.H13_MARK;
function isThenable(x) { return x !== null && (typeof x === "object" || typeof x === "function") && typeof x.then === "function"; }
function walk(x, fn) {
  if (Array.isArray(x)) return x.map((v) => walk(v, fn));
  if (x !== null && typeof x === "object") { const o = {}; for (const [k, v] of Object.entries(x)) { const r = fn(k, v); if (r !== DROP) o[k] = walk(r === KEEP ? v : r, fn); } return o; }
  return x;
}
const DROP = Symbol("drop");
const KEEP = Symbol("keep");
function mutate(res) {
  let out = res;
  let applied = true;
  if (MODE === "ask") {
    let n = 0;
    const swap = (x) => { if (x === "allow") { n++; return "ask"; } if (Array.isArray(x)) return x.map(swap); if (x !== null && typeof x === "object") { const o = {}; for (const [k, v] of Object.entries(x)) o[k] = swap(v); return o; } return x; };
    out = swap(res); applied = n > 0;
  } else if (MODE === "undefined") { out = undefined; }
  else if (MODE === "null") { out = null; }
  else if (MODE === "unknown-kind") { out = { kind: "h13-no-such-kind" }; }
  else if (MODE === "refusal-no-reason") {
    let n = 0;
    out = walk(res, (k) => { if (k === "reason") { n++; return DROP; } return KEEP; });
    applied = n > 0;
  }
  if (MARK) fs.writeFileSync(MARK, JSON.stringify({ mode: MODE, applied, hadResult: res !== undefined && res !== null }));
  return out;
}
function wrap(fn) { return (...args) => { const res = fn(...args); return isThenable(res) ? res.then(mutate) : mutate(res); }; }
${exportsBlock}
`;
}

test("AC-H13: typed fail-closed output (PT-15): with the gate module returning each odd shape, the hook exits 2 or emits a deny JSON for every shape; silence only for an exact allow verdict", () => {
  const sb = createGateSandbox();
  const hookSource = fs.readFileSync(sb.hookPath, "utf8");
  const names = gateImportNames(hookSource);
  assert.ok(names !== undefined, "the hook must import its gate function(s) from src/policy/gate/decide-tool-call.ts (the plan's gate module); no such import found, so the gate is not built or not wired into the hook");
  const gateDir = path.join(sb.root, "src", "policy", "gate");
  const gateFile = path.join(gateDir, "decide-tool-call.ts");
  assert.ok(fs.existsSync(gateFile), `the sandbox copy must contain ${gateFile}`);
  fs.renameSync(gateFile, path.join(gateDir, "decide-tool-call.real.ts"));
  fs.writeFileSync(gateFile, wrapperSource(names), "utf8");

  const scenarios: { mode: string; tool: () => GateRun; expectBlocking: boolean }[] = [];
  const markFile = (mode: string): string => path.join(sb.root, `h13-mark-${mode}.json`);
  const runMode = (mode: string, toolName: string, toolInput: unknown): GateRun =>
    sb.call(toolName, toolInput, { H13_MODE: mode, H13_MARK: markFile(mode) });
  scenarios.push({ mode: "control", tool: () => runMode("control", "Bash", { command: BASH_GET }), expectBlocking: false });
  scenarios.push({ mode: "ask", tool: () => runMode("ask", "Bash", { command: BASH_GET }), expectBlocking: true });
  scenarios.push({ mode: "undefined", tool: () => runMode("undefined", "Bash", { command: BASH_GET }), expectBlocking: true });
  scenarios.push({ mode: "null", tool: () => runMode("null", "Bash", { command: BASH_GET }), expectBlocking: true });
  scenarios.push({ mode: "unknown-kind", tool: () => runMode("unknown-kind", "Bash", { command: BASH_GET }), expectBlocking: true });
  scenarios.push({ mode: "refusal-no-reason", tool: () => runMode("refusal-no-reason", "Write", {}), expectBlocking: true });

  for (const s of scenarios) {
    const run = s.tool();
    const mark = markFile(s.mode);
    assert.ok(fs.existsSync(mark), `H13 ${s.mode}: the hook never called the (wrapped) gate function, so the odd shape was never delivered; ${describeRun(run)}`);
    const record = JSON.parse(fs.readFileSync(mark, "utf8")) as { applied: boolean };
    assert.equal(record.applied, true, `H13 ${s.mode}: the odd shape could not be derived from the real gate result (the harness mutation did not apply); ${describeRun(run)}`);
    if (s.expectBlocking) {
      assert.ok(isBlocking(run), `H13 ${s.mode}: the hook must exit 2 (with stderr) or emit a deny JSON, never stay silent or allow; got ${describeRun(run)}`);
    } else {
      assertSilentAllow(run, `H13 ${s.mode} (pass-through control: an exact allow verdict is the ONLY silent outcome)`);
    }
  }
});
